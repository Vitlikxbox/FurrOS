//! Interface strings in the four FurrOS languages. The language comes from furrboot.conf
//! (written by furrboot-update from the system language).

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Lang { Ru, En, Pl, Es }

impl Lang {
    pub fn from_code(s: &str) -> Lang {
        match s.get(..2).unwrap_or("") {
            "ru" | "uk" | "be" | "kk" => Lang::Ru,
            "pl" => Lang::Pl,
            "es" => Lang::Es,
            _ => Lang::En,
        }
    }
}

